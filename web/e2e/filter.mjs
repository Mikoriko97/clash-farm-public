// Що smoke-тест не вважає помилкою консолі. Кожен виняток — з причиною; новий виняток додавати лише після розслідування (краще виправити).
export const ALLOWED = [
  // (порожньо: усе, що друкують Godot і React як помилку, має бути виправлено)
];

/** Чи рядок консолі валить smoke-тест (не збігається з жодним дозволеним шаблоном). */
export function fatal(line, allowed = ALLOWED) {
  return !allowed.some((re) => re.test(line));
}
