/** Object form after a verb ("Plant …", "Harvest …", "Remove …", "Place …"). English has no
 *  cases, so this is the plain label; the helper stays so callers keep working. */
export function accusative(id: string): string {
  return ITEM_LABEL[id] ?? id;
}

/** First letter up: labels stay lowercase for use inside sentences, titles start capitalised. */
export function cap(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** Item name as a title (tile, row, sheet heading). */
export function titleOf(id: string): string {
  return cap(ITEM_LABEL[id] ?? id);
}
